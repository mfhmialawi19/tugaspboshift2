package Tugas5;


public class Soal8 {
    public void foreach(){
        int[] arrayNilai = {10, 20, 30, 40, 50};

        System.out.println("Nilai dlm array menggunakan foreach:");
        for (int nilai : arrayNilai) {
            System.out.print(nilai + " ");
        }
        System.out.println();
    }
}
